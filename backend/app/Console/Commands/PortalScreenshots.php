<?php

namespace App\Console\Commands;

use App\Models\AdSupportArticle;
use App\Models\AdSupportCollection;
use App\Models\BlogPost;
use App\Models\Country;
use App\Models\HelpCenterArticle;
use App\Models\HelpCenterCategory;
use Illuminate\Console\Command;
use Symfony\Component\Process\Process;

/**
 * Optional helper: regenerates the section screenshots shown in the admin
 * "Portal content" editor. Thin wrapper around scripts/portal-screenshots.mjs
 * (Playwright + Chromium). See docs/PORTAL_SCREENSHOTS.md.
 */
class PortalScreenshots extends Command
{
    protected $signature = 'portal:screenshots
        {--base=http://portal.localhost:8000 : Base URL of a locally served portal (php artisan serve)}
        {--country= : Country site_code to render (default: first active country)}
        {--page= : Only this page_key from config/portal_sections.php (merges into the existing config/portal_bands.php)}';

    protected $description = 'Capture portal band screenshots (local render) and regenerate config/portal_bands.php';

    public function handle(): int
    {
        $country = $this->option('country')
            ?: Country::where('is_active', true)->orderByDesc('is_launched')->orderBy('name_en')->value('site_code');

        if (! $country) {
            $this->error('No active country found.');

            return self::FAILURE;
        }

        $config = [
            'base' => $this->option('base'),
            'country' => $country,
            'params' => [
                'collection' => AdSupportCollection::where('is_active', true)->value('slug'),
                'article' => AdSupportArticle::published()->value('slug'),
                'category' => HelpCenterCategory::where('is_active', true)->value('slug'),
                'slug' => BlogPost::published()->value('slug'),
                'help_article' => HelpCenterArticle::published()->value('slug'),
            ],
            'sections' => config('portal_sections'),
            'pairs' => $this->seededPairs(),
        ];

        $tmp = tempnam(sys_get_temp_dir(), 'portal-shots-');
        file_put_contents($tmp, json_encode($config, JSON_UNESCAPED_UNICODE));

        $bandsTmp = tempnam(sys_get_temp_dir(), 'portal-bands-');
        $cmd = ['node', base_path('scripts/portal-screenshots.mjs'), '--config='.$tmp, '--bands-out='.$bandsTmp];
        if ($this->option('page')) {
            $cmd[] = '--page='.$this->option('page');
        }

        $process = new Process($cmd, base_path(), null, null, 1800);
        $process->run(fn ($type, $buffer) => $this->output->write($buffer));
        @unlink($tmp);

        if (! $process->isSuccessful()) {
            @unlink($bandsTmp);

            return self::FAILURE;
        }

        $bands = json_decode((string) file_get_contents($bandsTmp), true) ?: [];
        @unlink($bandsTmp);

        $target = config_path('portal_bands.php');
        if ($this->option('page') && is_file($target)) {
            $bands = array_replace(require $target, $bands);
        }
        file_put_contents($target, "<?php\n\n".self::HEADER."\nreturn ".$this->export($bands, 0).";\n");
        $this->info('Wrote config/portal_bands.php ('.count($bands).' pages). Run vendor/bin/pint config/portal_bands.php if needed.');

        return self::SUCCESS;
    }

    private const HEADER = <<<'TXT'
/*
|--------------------------------------------------------------------------
| Portal content bands (GENERATED by `php artisan portal:screenshots`)
|--------------------------------------------------------------------------
|
| One entry per visual band of each portal page (DOM order). `image` is the
| file stem of public/images/portal-sections/{image}.{en|ar}.png (null = none).
| `blocks` are [page_key, block_key] pairs and may point to other page keys.
| config/portal_sections.php stays the block-level source of truth.
*/
TXT;

    /**
     * @return list<array{0: string, 1: string}>
     */
    private function seededPairs(): array
    {
        $pairs = [];
        foreach (require database_path('seeders/data/portal_content.php') as $row) {
            $pairs[$row[0].'|'.$row[1]] = [$row[0], $row[1]];
        }

        return array_values($pairs);
    }

    private function export(mixed $value, int $level): string
    {
        if (! is_array($value)) {
            return var_export($value, true);
        }
        if ($value === []) {
            return '[]';
        }
        $pad = str_repeat('    ', $level + 1);
        $isList = array_is_list($value);
        if ($isList && count($value) === 2 && is_string($value[0]) && is_string($value[1])) {
            return '['.var_export($value[0], true).', '.var_export($value[1], true).']';
        }
        $lines = [];
        foreach ($value as $k => $v) {
            $lines[] = $pad.($isList ? '' : var_export($k, true).' => ').$this->export($v, $level + 1).',';
        }

        return "[\n".implode("\n", $lines)."\n".str_repeat('    ', $level).']';
    }
}
